#!/usr/bin/env python3
"""Synchronize the color contract into web/admin, SwiftUI, Compose and Android XML.
Run with --check in validation; it reports stale files without writing them.
"""
import json
import re
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
colors = json.loads((ROOT / 'design/tokens/colors.json').read_text())['colors']
check = '--check' in sys.argv
stale = []
def output(path, text):
    path = ROOT / path
    if path.exists() and path.read_text() == text: return
    stale.append(str(path.relative_to(ROOT)))
    if not check:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)

aliases = {
 'bg-top':'surface','bg-mid':'surface-intermediate','bg-bottom':'surface',
 'glass-fill':'surface-card','glass-fill-strong':'surface-card','glass-soft':'surface-raised',
 'glass-stroke':'border','text-main':'text','text-soft':'text-muted','gold':'gold',
 'blue-pill':'primary','rose':'berry','button-top':'primary','button-bottom':'primary-strong',
 'purple-outline':'border-strong','tab-fill':'surface','tab-border':'border',
 'tab-inactive':'text-muted','tab-active':'primary','selected-fill':'surface-raised',
 'admin-text':'text','admin-muted':'text-muted','admin-label':'text','admin-input':'surface-card','admin-border':'border'
}
lines = ['// Generated by scripts/sync-color-contract.py. Edit design/tokens/colors.json.', ':root {']
lines += [f'  --sanctuary-{name}: {value};' for name, value in colors.items()]
lines += [f'  --{name}: var(--sanctuary-{role});' for name, role in aliases.items()]
lines += ['  --glass-overlay: transparent;', '  --sanctuary-scrim: color-mix(in srgb, var(--sanctuary-hero) 55%, transparent);',
          '  --sanctuary-shadow: color-mix(in srgb, var(--sanctuary-text) 8%, transparent);', '  color-scheme: light;', '}','']
output('apps/web/src/styles/_colors.scss', '\n'.join(lines))
# Stable adapter names retain compatibility with current native call sites.
ios_names = ['homeSurface','homeSurfaceRaised','cardBackground','cardBackgroundElevated','gradientMid','homeInk','homeMuted','glowBlue','primaryButtonBottom','onAccent','heroBase','border','purpleOutline','errorText','errorSurface','warningText','warningSurface','successText','glowGold','glowRose','advent','christmas','lent','easter','ordinary','todayHighlight','qrCanvas']
android_names = ['SanctuaryHomeSurface','SanctuaryHomeSurfaceRaised','SanctuaryCard','SanctuaryCardElevated','SanctuaryGradientMid','SanctuaryHomeInk','SanctuaryHomeMuted','SanctuaryBlue','SanctuaryPrimaryStrong','SanctuaryOnAccent','SanctuaryHeroBase','SanctuaryTabBorder','SanctuaryBorderStrong','SanctuaryError','SanctuaryErrorSurface','SanctuaryWarning','SanctuaryWarningSurface','SanctuarySuccess','SanctuaryGlowGold','SanctuaryGlowRose','SanctuaryAdvent','SanctuaryChristmas','SanctuaryLent','SanctuaryEaster','SanctuaryOrdinary','SanctuaryToday','SanctuaryQrCanvas']
roles = ['surface','surface-raised','surface-card','surface-elevated','surface-intermediate','text','text-muted','primary','primary-strong','on-accent','hero','border','border-strong','error','error-surface','warning','warning-surface','success','gold','berry','advent','christmas','lent','easter','ordinary','today','qr-canvas']
assert len(ios_names) == len(android_names) == len(roles) and set(roles) == set(colors)
for path, names, platform in [
 ('apps/ios/Sanctuary/UI/AppTheme.swift', ios_names, 'ios'),
 ('apps/android/app/src/main/java/app/sanctuary/android/ui/theme/Color.kt', android_names, 'android')]:
    text = (ROOT / path).read_text()
    additions = []
    for role, name in zip(roles, names):
        value = colors[role]
        declaration = f'    static let {name} = Color(hex: "{value}")' if platform == 'ios' else f'val {name} = Color(0xFF{value[1:]})'
        pattern = rf'^\s*static let {name} = [^\n]+' if platform == 'ios' else rf'^val {name} = [^\n]+'
        if re.search(pattern, text, re.M): text = re.sub(pattern, declaration, text, flags=re.M)
        else: additions.append(declaration)
    if additions:
        if platform == 'ios': text = text.replace('enum AppTheme {', 'enum AppTheme {\n'+'\n'.join(additions))
        else: text = text.replace('import androidx.compose.ui.graphics.Color', 'import androidx.compose.ui.graphics.Color\n\n'+'\n'.join(additions))
    output(path, text)
xml = ['<?xml version="1.0" encoding="utf-8"?>','<!-- Generated by scripts/sync-color-contract.py. -->','<resources>']
xml += [f'    <color name="sanctuary_{role.replace("-","_")}">{value}</color>' for role, value in colors.items()]
xml += ['</resources>','']
output('apps/android/app/src/main/res/values/colors.xml', '\n'.join(xml))
# Both embedded reading viewers receive identical host-scoped CSS tokens.
template = (ROOT/'design/tokens/readings-theme.js.template').read_text()
definitions = ':root {\n'+'\n'.join(f'  --sanctuary-{role}: {value};' for role,value in colors.items())+'\n}'
reader = template.replace('__COLOR_VARIABLES__', definitions)
output('apps/ios/Sanctuary/Resources/readings-theme.js', reader)
output('apps/android/app/src/main/assets/readings-theme.js', reader)
# Keep system launch surfaces in the same palette as the runtime UI.
launch_path = 'apps/ios/Sanctuary/Assets.xcassets/LaunchBackground.colorset/Contents.json'
launch = json.loads((ROOT/launch_path).read_text())
for name,offset in [('red',1),('green',3),('blue',5)]:
    launch['colors'][0]['color']['components'][name] = f"{int(colors['surface'][offset:offset+2],16)/255:.6f}"
output(launch_path, json.dumps(launch,indent=2)+'\n')
launch_path = 'apps/ios/Sanctuary/LaunchScreen.storyboard'
launch = (ROOT/launch_path).read_text()
rgb=[int(colors['hero'][i:i+2],16)/255 for i in [1,3,5]]
launch=re.sub(r'(<color key="backgroundColor" )red="[^"]+" green="[^"]+" blue="[^"]+"',
              r'\g<1>'+f'red="{rgb[0]:.10f}" green="{rgb[1]:.10f}" blue="{rgb[2]:.10f}"', launch)
output(launch_path,launch)
if stale:
    print(('Stale color adapters: ' if check else 'Updated color adapters: ') + ', '.join(stale))
    if check: sys.exit(1)
else: print('All platform color adapters match the contract.')
